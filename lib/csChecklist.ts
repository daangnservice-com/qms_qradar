import type { CriterionReviewScope } from "./promptTypes";

export interface CsCriterion {
  id: number;
  category: string; // 대분류 (= 뷰 parent_name)
  label: string; // 소분류 (= 뷰 name)
  /** @deprecated fields.definition 권장. 하위호환용 */
  hint: string;
  /** definition / good / bad / exception 등 (필드 키는 설정으로 확장) */
  fields?: Record<string, string>;
  /** 수기 검수 적용 범위. 기본값은 발화별. */
  reviewScope?: CriterionReviewScope;
}

function item(
  id: number,
  category: string,
  label: string,
  fields: { definition: string; good: string; bad: string; exception: string },
  opts?: { reviewScope?: CriterionReviewScope },
): CsCriterion {
  return {
    id,
    category,
    label,
    hint: fields.definition,
    fields,
    reviewScope: opts?.reviewScope,
  };
}

