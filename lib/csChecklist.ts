// 프롬프트에 넣을 체크리스트 지시 블록. 근거 강제 + 보수적 판정으로 환각을 통제한다.
export function buildChecklistPromptBlock(): string {
  const items = CS_CHECKLIST.map((c) => `[${c.id}] (${c.category}) ${c.label}\n     └ 판단기준: ${c.hint}`).join("\n");
  const n = CS_CHECKLIST.length;
  return [
    "── CS 영역 감점 체크리스트 ──",
    `아래 ${n}개 항목 각각에 대해, 이 통화에서 '위반'이 있었는지 판단해 csChecklist로 응답하세요.`,
    "규칙(반드시 지킬 것):",
    "- 위반이 **명확할 때만** violated=true. 근거(전사 인용문 quote + 시각 atSec)를 evidence에 **반드시** 넣으세요.",
    "- 근거를 댈 수 없으면 violated=false. **애매하면 false**(과잉 지적 금지 — 정확도 우선).",
    "- reason에는 판정 이유를 한 줄로. id는 아래 번호를 **그대로** 사용(임의 변경 금지).",
    `- ${n}개 항목을 **모두** 배열에 포함하세요(위반 아니어도 violated=false로).`,
    "",
    items,
  ].join("\n");
}
